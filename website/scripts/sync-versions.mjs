import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const websiteRoot = path.resolve(__dirname, '..')
const repoRoot = path.resolve(websiteRoot, '..')
const tomlPath = path.join(repoRoot, 'gradle/libs.versions.toml')
const versionsTs = path.join(websiteRoot, 'src/lib/versions.ts')

function readTomlVersions(source) {
  const library = source.match(/^libraryVersion\s*=\s*"([^"]+)"/m)?.[1]
  const icons = source.match(/^iconsVersion\s*=\s*"([^"]+)"/m)?.[1]
  if (!library || !icons) {
    throw new Error(
      'gradle/libs.versions.toml 里需要 libraryVersion 和 iconsVersion（例如 libraryVersion = "0.2.0"）',
    )
  }
  return { library, icons }
}

function patchFile(filePath, library, icons) {
  if (!fs.existsSync(filePath)) return
  const before = fs.readFileSync(filePath, 'utf8')
  const after = before
    .replace(/io\.github\.ctoo-uxd:genev4-icons:\d+\.\d+\.\d+/g, `io.github.ctoo-uxd:genev4-icons:${icons}`)
    .replace(/io\.github\.ctoo-uxd:genev4:\d+\.\d+\.\d+/g, `io.github.ctoo-uxd:genev4:${library}`)
    .replace(/\{\{LIBRARY_VERSION\}\}/g, library)
    .replace(/\{\{ICONS_VERSION\}\}/g, icons)
  if (after !== before) {
    fs.writeFileSync(filePath, after)
    console.log(`versions: patched ${path.relative(repoRoot, filePath)}`)
  }
}

const { library, icons } = readTomlVersions(fs.readFileSync(tomlPath, 'utf8'))

fs.writeFileSync(
  versionsTs,
  `/** Generated by scripts/sync-versions.mjs — do not edit. */\n` +
    `export const LIBRARY_VERSION = '${library}'\n` +
    `export const ICONS_VERSION = '${icons}'\n`,
)

const staticFiles = [
  path.join(repoRoot, 'README.md'),
  path.join(repoRoot, 'icons/README.md'),
  path.join(repoRoot, 'docs/PUBLISH.md'),
  path.join(repoRoot, 'docs/getting-started.md'),
]

for (const file of staticFiles) {
  patchFile(file, library, icons)
}

console.log(`versions: library=${library} icons=${icons}`)
